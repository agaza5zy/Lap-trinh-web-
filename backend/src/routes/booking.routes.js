import { asyncHandler } from '../middleware/asyncHandler.js';
import { Router } from 'express';
import * as controller from '../controllers/booking.controller.js';
import { authenticate } from '../middleware/auth.js';
const router = Router();
router.post('/', authenticate, asyncHandler(controller.create));
router.get('/my', authenticate, asyncHandler(controller.myBookings));
router.get('/lookup/:code', asyncHandler(controller.getByCode));
router.patch('/:id/cancel', authenticate, asyncHandler(controller.cancel));
export default router;
