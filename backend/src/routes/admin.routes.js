import { asyncHandler } from '../middleware/asyncHandler.js';
import { Router } from 'express';
import * as controller from '../controllers/admin.controller.js';
import { authenticate } from '../middleware/auth.js';
import { requireRole } from '../middleware/role.js';
const router = Router();
router.use(authenticate, requireRole('admin', 'staff'));
router.get('/stats', asyncHandler(controller.stats));
router.get('/hotels', asyncHandler(controller.listHotels));
router.get('/bookings', asyncHandler(controller.listBookings));
router.patch('/bookings/:id/status', asyncHandler(controller.updateBookingStatus));
router.get('/rooms', asyncHandler(controller.listRooms));
router.post('/rooms', requireRole('admin'), asyncHandler(controller.createRoomType));
router.post('/room-types/:id/rooms', requireRole('admin'), asyncHandler(controller.addRoomUnit));
router.patch('/rooms/:id', asyncHandler(controller.updateRoom));
router.get('/users', requireRole('admin'), asyncHandler(controller.listUsers));
router.patch('/users/:id/status', requireRole('admin'), asyncHandler(controller.updateUserStatus));
router.patch('/users/:id/role', requireRole('admin'), asyncHandler(controller.updateUserRole));
export default router;
